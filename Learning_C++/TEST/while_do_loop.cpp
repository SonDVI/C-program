#include <iostream>
using namespace std;

int main() {
    int a = 5;
    do {
        cout << a << endl;//perform the code
        a++;//increment or decrement the value

    }while(a<10);//condition
}
/*do-while loop is a variant of the while loop, with the key difference
is it's running first and checking the condition later, ensuring that the loop
body is executed at least once.*/