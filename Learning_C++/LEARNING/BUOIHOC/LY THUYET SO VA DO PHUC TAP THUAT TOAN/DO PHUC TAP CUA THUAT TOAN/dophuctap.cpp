/*
        ĐỘ PHỨC TẠP CỦA THUẬT TOÁN

- Độ phức tạp của thuật toán đo bằng cách sử dụng kí hiệu O (Big O notation) , kí hiệu :
    >> O(f(n)) : thuật toán có độ phức tạp về thời gian của f(n) (time complexity). Với n là kích thước của input.

        >> EX: n : input = 10 ^ 6 --> O(n^2) = 10^12 -> time: 10^12 / 10^8 = 10^4s.
            --> O(n) = 10^6 -> time: 10^6 / 10^8 = 0.01s.

- Mức độ phức tạp của thuật toán được xếp hạng theo thứ tự tăng dần như sau:
    - O(1) < O(log n) < O(sqrt(n)) < O(n) < O(n log n) < O(n * sqrt(n)) < O(n^2) < O(n^3) < O(2^n) < O(n!) <...

    - Nếu độ phức tạp là 1 đa thức. Ví dụ :
    O(4n^3 +7n +5) = O(n^3) vì n^3 là bậc cao nhất.


*/