#include <cmath> // Thư viện này cung cấp các hàm toán học như sqrt, pow, abs, v.v.
using namespace std;

// Một số hàm toán học phổ biến trong C++:


// sqrt(x): trả về căn bậc hai của x. EX: sqrt(16) = 4


// pow(x, y): trả về x mũ y. EX: pow(2, 3) = 8


// abs(x): trả về giá trị tuyệt đối của x. EX: abs(-5) = 5


// ceil(x): trả về giá trị nguyên lớn nhất không nhỏ hơn x. EX: ceil


// floor(x): trả về giá trị nguyên nhỏ nhất không lớn hơn x. EX: floor(3.7) = 3


// round(x): trả về giá trị nguyên gần nhất với x. EX: round(3.5) = 4, round(3.4) = 3


//max(a, b): trả về giá trị lớn hơn giữa a và b. EX: max(5, 10) = 10


//min(a, b): trả về giá trị nhỏ hơn giữa a và b. EX: min(5, 10) = 5