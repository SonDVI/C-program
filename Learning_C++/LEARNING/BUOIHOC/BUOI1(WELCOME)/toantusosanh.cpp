#include <iostream>

using namespace std;

int main() {
    int a = 5, b = 3;
    cout << (a > b) << endl; // true (1)
    cout << (a < b) << endl; // false (0)
    cout << (a == b) << endl; // false (0)
    cout << (a != b) << endl; // true (1)
    cout << (a >= b) << endl; // true (1)
    cout << (a <= b) << endl; // false (0)
    return 0;
}